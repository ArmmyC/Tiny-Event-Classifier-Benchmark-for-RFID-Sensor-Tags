from __future__ import annotations

import argparse
from pathlib import Path
import sys

import numpy as np

from .classifiers import FSMClassifier, LUTLikeClassifier, ThresholdClassifier, TinySNNV2Classifier
from .config import load_config
from .dataset import DatasetConfig, generate_noisy_event_dataset


def export_rtl_vectors(
    config_path: str | Path,
    output_path: str | Path,
    input_dir: str | Path | None = None,
    limit: int | None = None,
) -> Path:
    """Export samples and Python baseline predictions as a SystemVerilog include."""
    config = load_config(config_path)
    dataset_settings = config["dataset"]
    if int(dataset_settings["input_width"]) < 3:
        raise ValueError("RTL baselines require dataset.input_width >= 3")

    if input_dir is None:
        inputs, labels = generate_noisy_event_dataset(
            DatasetConfig.from_mapping(
                dataset_settings, config["scenario"], config.get("scenario_suite")
            )
        )
    else:
        directory = Path(input_dir)
        inputs = np.load(directory / "inputs.npy", allow_pickle=False)
        labels = np.load(directory / "labels.npy", allow_pickle=False)

    if inputs.ndim != 3 or labels.shape != (inputs.shape[0],):
        raise ValueError("RTL vector inputs must have shape [samples, cycles, channels]")
    if limit is not None:
        if limit <= 0:
            raise ValueError("limit must be greater than zero")
        inputs = inputs[:limit]
        labels = labels[:limit]
    if inputs.shape[0] == 0:
        raise ValueError("RTL vector export requires at least one sample")

    classifier_settings = config["classifiers"]
    threshold_settings = classifier_settings["threshold"]
    fsm_settings = classifier_settings["fsm"]
    lut_settings = classifier_settings["lut_like"]
    tiny_snn_v2_settings = classifier_settings["tiny_snn_v2"]
    threshold = ThresholdClassifier(**threshold_settings)
    fsm = FSMClassifier(pattern=(0, 1, 2), **fsm_settings)
    lut_like = LUTLikeClassifier(pattern=(0, 1, 2), **lut_settings)
    tiny_snn_v2 = TinySNNV2Classifier(**tiny_snn_v2_settings)

    predictions = {
        "threshold": threshold.predict(inputs),
        "fsm": fsm.predict(inputs),
        "lut_like": lut_like.predict(inputs),
        "tiny_snn_v2": tiny_snn_v2.predict(inputs),
    }
    width = int(inputs.shape[2])
    digits = max(1, (width + 3) // 4)
    lines = [
        "// Generated by python/export_rtl_vectors.py; do not edit.",
        f"localparam int RTL_NUM_SAMPLES = {inputs.shape[0]};",
        f"localparam int RTL_SEQ_LEN = {inputs.shape[1]};",
        f"localparam int RTL_INPUT_WIDTH = {width};",
        f"localparam int RTL_THRESHOLD_MIN_ACTIVE_CYCLES = {threshold.min_active_cycles};",
        f"localparam int RTL_THRESHOLD_MIN_TOTAL_SPIKES = {threshold.min_total_spikes};",
        f"localparam int RTL_FSM_MAX_GAP = {fsm.max_gap};",
        f"localparam int RTL_LUT_MAX_TOTAL_SPIKES = {lut_like.max_total_spikes};",
        "logic [RTL_INPUT_WIDTH-1:0] vector_samples [0:RTL_NUM_SAMPLES*RTL_SEQ_LEN-1];",
        "logic expected_threshold [0:RTL_NUM_SAMPLES-1];",
        "logic expected_fsm [0:RTL_NUM_SAMPLES-1];",
        "logic expected_lut_like [0:RTL_NUM_SAMPLES-1];",
        "logic expected_tiny_snn_v2 [0:RTL_NUM_SAMPLES-1];",
        "initial begin",
    ]
    flat_inputs = inputs.reshape(-1, width)
    for index, row in enumerate(flat_inputs):
        value = sum(int(bit) << bit_index for bit_index, bit in enumerate(row))
        lines.append(f"    vector_samples[{index}] = {width}'h{value:0{digits}x};")
    for name, values in predictions.items():
        for index, value in enumerate(values):
            lines.append(f"    expected_{name}[{index}] = 1'b{int(value)};")
    lines.extend(["end", ""])

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="ascii")
    return output


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Export Python-golden RTL baseline vectors.")
    parser.add_argument("--config", type=Path, default=Path("configs/temporal_hard.json"))
    parser.add_argument("--output", type=Path, default=Path("results/rtl/vectors.svh"))
    parser.add_argument("--input-dir", type=Path)
    parser.add_argument("--limit", type=int)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        output = export_rtl_vectors(args.config, args.output, args.input_dir, args.limit)
        print(f"RTL vectors written: {output}")
        return 0
    except (ValueError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
